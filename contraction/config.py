import os

# ==============================================================================
# 1. 数据输入与输出配置
# ==============================================================================
# 股票池来源文件路径:
# - 支持 .csv 或 .txt 文档，第一列包含股票代码（纯数字或带前缀均可）
# - 若设置为 None 或 ""，程序将自动扫描全市场（沪深A股+北交所，约5000+只）
STOCK_POOL_FILE = "stock.csv"
# STOCK_POOL_FILE = ""

# 结果导出目录
OUTPUT_DIR = "./output"


# ==============================================================================
# 2. 核心量化策略阈值（可按需调整）
# ==============================================================================
# [长期放量] 90个交易日内，单日最高换手率阈值(%)
# 含义: 筛选出90天内至少有过一次主力放量异动超过此阈值的股票
MIN_TURNOVER_90D = 9.0   # 默认: 10.0%

# [中期放量] 30个交易日内（排除考察日当天），单日最高换手率阈值(%)
# 含义: 筛选出30天内波峰活跃度超过此阈值的股票
MIN_TURNOVER_30D = 2.9    # 默认: 2.9%

# [缩量倍数下限] 30天最高换手率 / 近3天最低换手率
# 含义: 达到多少倍以上的极端地量才入选。例如 6.0 代表缩减到峰值的 1/6 以下
MIN_SHRINK_RATIO = 6.0    # 默认: 6.0 倍

# [缩量倍数上限] （可选保护）
# 若不想限制上限（即缩量8倍、10倍依然要），请设置为 None；若严格限制在 6~8 倍，可设置为 8.0
MAX_SHRINK_RATIO = None   # 例如: 8.0 或 None

# [防除零保护] 近3天最低换手率的下限值(%)
# 含义: 排除因为连续一字跌停、长期停牌导致换手率为 0.00 的虚假放量标的
MIN_VALID_TURNOVER = 0.01 # 默认: 0.01%


# ==============================================================================
# 3. 交易日统计窗口配置（单位: 交易日 K 线根数）
# ==============================================================================
LONG_WINDOW = 90          # 长期考察窗口天数（90个交易日）
SHORT_WINDOW = 30         # 中期考察窗口天数（30个交易日）
CHECK_WINDOW = 3          # 近期缩量考察天数（近3个交易日：含 T, T-1, T-2）

# 请求的 K 线根数（必须大于 LONG_WINDOW + CHECK_WINDOW，富余量用于指标计算）
KLINE_COUNT = 160


# ==============================================================================
# 4. 网络抓取与并发调度配置
# ==============================================================================
MAX_WORKERS = 16          # 线程池并发线程数
REQUEST_TIMEOUT = 2.0     # 单个 HTTP 请求超时秒数
SNAPSHOT_BATCH_SIZE = 80  # 腾讯极速行情快照单次拉取数量（最大支持 80-100 只）